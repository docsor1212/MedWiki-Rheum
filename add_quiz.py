def process_file(filepath):
    filename = os.path.basename(filepath)
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()

    if '自测题' in content:
        return False, 'already has quiz'

    quizzes = QUIZZES.get(filename)
    if not quizzes:
        # Generate generic quizzes based on filename
        quizzes = generate_generic_quizzes(filename, content)

    items = []
    for i, (q, a) in enumerate(quizzes, 1):
        items.append(make_quiz_item(i, q, a))

    quiz_html = make_quiz_box(items)

    # Find insertion point - before 参考文献 or 文献来源
    ref_marker = '<div class="sh">📖 参考文献</div>'
    ref_marker2 = '<div class="sh">📖 文献来源</div>'

    if ref_marker in content:
        content = content.replace(ref_marker, quiz_html + '\n    ' + ref_marker)
    elif ref_marker2 in content:
        content = content.replace(ref_marker2, quiz_html + '\n    ' + ref_marker2)
    else:
        return False, 'no reference marker found'

    with open(filepath, 'w', encoding='utf-8') as f:
        f.write(content)
    return True, f'added {len(quizzes)} questions'


