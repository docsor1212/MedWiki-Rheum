def main():
    cases_dir = CASES_DIR
    files = sorted([f for f in os.listdir(cases_dir) if f.startswith('case_') and f.endswith('.html')])

    success = 0
    failed = []
    for f in files:
        filepath = os.path.join(cases_dir, f)
        ok, msg = process_file(filepath)
        if ok:
            success += 1
            print(f'✅ {f}: {msg}')
        else:
            failed.append((f, msg))
            print(f'❌ {f}: {msg}')

    print(f'\n总计: {success}/{len(files)} 成功, {len(failed)} 失败')
    if failed:
        for f, msg in failed:
            print(f'  失败: {f} - {msg}')

if __name__ == '__main__':
    main()
